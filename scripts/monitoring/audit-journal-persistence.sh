#!/usr/bin/env bash
# audit-journal-persistence.sh — read-only audit of systemd-journald
# persistence across the fleet.
#
# For each node it collects, over SSH (or locally with --local):
#   * the effective Storage= value from journald.conf and its drop-ins
#     (last assignment wins, in journald's own read order)
#   * whether /var/log/journal exists
#   * how many boots the journal on disk knows about
#     (journalctl --list-boots; more than the current boot is direct
#     evidence that entries survive reboots)
#   * journal disk usage (journalctl --disk-usage)
# and prints one verdict row per node:
#   PERSISTENT  journal is configured to survive reboots
#   VOLATILE    journal is lost at reboot (or not kept at all)
#   UNREACHABLE the node did not answer over SSH
#   ERROR       the node answered but the evidence was incomplete
#
# The audit changes nothing. With --write-fixes DIR it also writes
# one fix-<node>.sh per VOLATILE node: an idempotent script to run
# on that node with sudo, which sets Storage=persistent through a
# drop-in, creates /var/log/journal via systemd-tmpfiles, restarts
# systemd-journald, and verifies the result.
#
# Usage:
#   audit-journal-persistence.sh [--write-fixes DIR] [node ...]
#   audit-journal-persistence.sh --local
# Default nodes: pi0 pi1 pi2 pi3 pi4 neo1 (pi3 included; while it is
# down for its rebuild it reports UNREACHABLE, which is the truth).
#
# Exit codes: 0 = every reached node persistent; 1 = at least one
# VOLATILE; 2 = at least one UNREACHABLE or ERROR and none volatile.
# AUDIT_ROOT (testing only): prefix a fixture tree in --local mode.
set -u

NODES=(pi0 pi1 pi2 pi3 pi4 neo1)
LOCAL=0
FIXDIR=""
while [ $# -gt 0 ]; do
  case "$1" in
    --local) LOCAL=1; shift ;;
    --write-fixes) FIXDIR="${2:?--write-fixes needs a directory}"; shift 2 ;;
    --) shift; break ;;
    -*) echo "unknown option: $1" >&2; exit 64 ;;
    *) break ;;
  esac
done
if [ $# -gt 0 ]; then NODES=("$@"); fi
# In --local mode without explicit node names there is exactly one
# subject: this host, under its own name.
if [ "$LOCAL" -eq 1 ] && [ $# -eq 0 ]; then NODES=("$(hostname)"); fi
if [ -n "$FIXDIR" ]; then mkdir -p "$FIXDIR"; fi

# The collector runs on the target and prints KEY=VALUE lines. One
# code path serves both transports: locally it runs directly, over
# SSH it is fed to the remote bash on stdin. AUDIT_ROOT prefixes
# every path for fixture testing and is empty in real runs.
collector() {
  cat <<'SNIPPET'
R="${AUDIT_ROOT:-}"
storage=""
for f in "$R"/etc/systemd/journald.conf "$R"/etc/systemd/journald.conf.d/*.conf "$R"/run/systemd/journald.conf.d/*.conf; do
  [ -f "$f" ] || continue
  v="$(grep -E '^[[:space:]]*Storage=' "$f" 2>/dev/null | tail -n 1 | cut -d= -f2- | tr -d '[:space:]')"
  [ -n "$v" ] && storage="$v"
done
echo "STORAGE=${storage:-unset}"
if [ -d "$R/var/log/journal" ]; then echo "DIR=yes"; else echo "DIR=no"; fi
boots="$(journalctl ${R:+--root=$R} --list-boots 2>/dev/null | awk '$1 ~ /^-?[0-9]+$/ {n++} END {print n+0}')"
echo "BOOTS=${boots:-0}"
usage="$(journalctl ${R:+--root=$R} --disk-usage 2>/dev/null | sed -n 's/.*take up \([^ ]*\).*/\1/p' | head -n 1)"
echo "DISK=${usage:-unknown}"
SNIPPET
}

write_fix() {
  local node="$1"
  local file="$FIXDIR/fix-$node.sh"
  cat > "$file" <<EOF
#!/usr/bin/env bash
# fix-$node.sh — make systemd-journald persistent on $node.
# Generated by audit-journal-persistence.sh; run ON $node with sudo.
# Idempotent: safe to run again after a partial application.
set -eu
mkdir -p /etc/systemd/journald.conf.d
printf '[Journal]\nStorage=persistent\n' > /etc/systemd/journald.conf.d/99-persistence.conf
systemd-tmpfiles --create --prefix /var/log/journal
systemctl restart systemd-journald
echo "Effective Storage after fix:"
grep -h -E '^[[:space:]]*Storage=' /etc/systemd/journald.conf /etc/systemd/journald.conf.d/*.conf 2>/dev/null | tail -n 1
echo "Boots now on record: \$(journalctl --list-boots | awk '\$1 ~ /^-?[0-9]+\$/ {n++} END {print n+0}')"
ls -ld /var/log/journal
echo "Persistence is proven at the NEXT reboot, when --list-boots shows 2 or more boots."
EOF
  chmod +x "$file"
}

any_volatile=0
any_unreached=0
printf '%-8s %-12s %-11s %-15s %-6s %-10s %s\n' NODE VERDICT STORAGE /var/log/journal BOOTS DISK "FIX / NOTE"
while IFS= read -r node; do
  if [ "$LOCAL" -eq 1 ]; then
    out="$(collector | AUDIT_ROOT="${AUDIT_ROOT:-}" bash -s 2>/dev/null)"
    rc=0
  else
    out="$(collector | ssh -o BatchMode=yes -o ConnectTimeout=5 -o StrictHostKeyChecking=accept-new "$node" 'bash -s' 2>/dev/null)"
    rc=$?
  fi
  if [ "$rc" -ne 0 ] || [ -z "$out" ]; then
    printf '%-8s %-12s %-11s %-15s %-6s %-10s %s\n' "$node" UNREACHABLE - - - - "node did not answer over SSH; if it is down for repair, remediate during its rebuild and re-run this audit"
    any_unreached=1
    continue
  fi
  storage="$(printf '%s\n' "$out" | sed -n 's/^STORAGE=//p')"
  dir="$(printf '%s\n' "$out" | sed -n 's/^DIR=//p')"
  boots="$(printf '%s\n' "$out" | sed -n 's/^BOOTS=//p')"
  disk="$(printf '%s\n' "$out" | sed -n 's/^DISK=//p')"
  if [ -z "$storage" ] || [ -z "$dir" ] || [ -z "$boots" ]; then
    printf '%-8s %-12s %-11s %-15s %-6s %-10s %s\n' "$node" ERROR "${storage:-?}" "${dir:-?}" "${boots:-?}" "${disk:-?}" "incomplete evidence; inspect the node directly"
    any_unreached=1
    continue
  fi
  case "$storage" in
    persistent) verdict=PERSISTENT; note="configured persistent" ;;
    volatile)   verdict=VOLATILE;   note="Storage=volatile keeps the journal in /run only" ;;
    none)       verdict=VOLATILE;   note="Storage=none keeps no journal at all" ;;
    auto|unset)
      if [ "$dir" = "yes" ]; then
        verdict=PERSISTENT; note="auto with /var/log/journal present"
      else
        verdict=VOLATILE; note="auto without /var/log/journal: journald stays in /run"
      fi
      ;;
    *) verdict=ERROR; note="unrecognized Storage value: $storage" ;;
  esac
  if [ "$verdict" = PERSISTENT ] && [ "$boots" -ge 2 ]; then
    note="$note; $boots boots on record prove survival"
  fi
  if [ "$verdict" = VOLATILE ]; then
    any_volatile=1
    if [ -n "$FIXDIR" ]; then
      write_fix "$node"
      note="$note; fix written to $FIXDIR/fix-$node.sh"
    else
      note="$note; re-run with --write-fixes DIR to generate its fix script"
    fi
  fi
  if [ "$verdict" = ERROR ]; then any_unreached=1; fi
  printf '%-8s %-12s %-11s %-15s %-6s %-10s %s\n' "$node" "$verdict" "$storage" "$dir" "$boots" "$disk" "$note"
done <<EOF
$(printf '%s\n' "${NODES[@]}")
EOF

if [ "$any_volatile" -eq 1 ]; then exit 1; fi
if [ "$any_unreached" -eq 1 ]; then exit 2; fi
exit 0
